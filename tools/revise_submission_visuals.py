"""Revise editable diagram sources; PNGs are rendered separately."""
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
BACKUP = ROOT / '.omx' / 'visuals-before-idea-review'
BACKUP.mkdir(parents=True, exist_ok=True)
for p in [*ROOT.glob('*.html'), *ROOT.glob('이미지/*.png')]:
    dest = BACKUP / p.relative_to(ROOT)
    dest.parent.mkdir(parents=True, exist_ok=True)
    if not dest.exists():
        shutil.copy2(p, dest)

def revise(name, replacements):
    p = ROOT / (name + '.html')
    s = p.read_text(encoding='utf-8-sig')
    for old, new in replacements:
        assert old in s, (name, old)
        s = s.replace(old, new)
    # Darken explanatory footnotes, and keep them inside full-page exports.
    s = s.replace('color:#9AA3AE', 'color:#667381')
    s = s.replace('</style>', '\n  .foot,.disc{gap:12px;line-height:1.6;flex-wrap:wrap}\n</style>')
    p.write_text(s, encoding='utf-8')

